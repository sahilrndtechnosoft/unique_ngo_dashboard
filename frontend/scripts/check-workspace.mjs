import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/utils/table-data.ts', import.meta.url), 'utf8');
const compiled = ts.transpile(source, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 });
const { csvCell, matchesTableFilter: matches } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
assert.equal(csvCell('a,"b"'), '"a,""b"""');
assert.equal(csvCell('=SUM(A1)'), '"\'=SUM(A1)"');
assert.equal(csvCell('  @SUM(A1)'), '"\'  @SUM(A1)"');
assert.equal(csvCell(null), '""');
assert.equal(matches('Active', 'active', 'equals'), true);
assert.equal(matches('Inactive', 'active', 'equals'), false);
assert.equal(matches('Member name', 'NAME', 'contains'), true);
assert.equal(matches('₹1,200', '1000', 'min'), true);
assert.equal(matches('invalid', '1000', 'min'), false);
assert.equal(matches('2026-09-24', '2026-09-01', 'after'), true);
assert.equal(matches('2026-09-24', '2026-09-01', 'before'), false);
assert.equal(matches('', '', 'equals'), true);
const shell = fs.readFileSync(new URL('../src/components/Layouts/DefaultLayout.tsx', import.meta.url), 'utf8');
assert.ok(shell.includes('branding.logoUrl ? mediaUrl(branding.logoUrl)'));
assert.ok(shell.includes('canAccess(auth.isSuperAdmin, auth.permissions, i.permission)'));
console.log('Workspace checks passed: filters, CSV safety, API logo, permission-aware navigation.');
